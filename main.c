void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
    if(GPIO_Pin == GPIO_PIN_0) // PA0 IR Sensor triggered
    {
        // Only trigger and print if armed AND alarm isn't already ringing
        if(system_armed && (intrusion_detected == 0))
        {
            intrusion_detected = 1;
            printf("\n*** INTRUDER ALERT! Motion Detected! ***\n");
        }
    }
}
