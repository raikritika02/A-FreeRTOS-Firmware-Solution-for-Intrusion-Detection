/**
  * @brief  Function implementing the SensorTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartSensorTask */
void StartSensorTask(void *argument)
{
  /* USER CODE BEGIN 5 */
  /* Infinite loop */
  for(;;)
  {
          if(HAL_GPIO_ReadPin(GPIOC, GPIO_PIN_13) == GPIO_PIN_RESET)
          {
              if(intrusion_detected == 1)
              {
                  intrusion_detected = 0;
                  system_armed = 1;
                  printf("Button Pressed: Alarm Reset. System Armed.\n");
              }
              else
              {
                  system_armed = !system_armed;
                  if(system_armed)
                  {
                      printf("Button Pressed: System ARMED.\n");
                  }
                  else
                  {
                      printf("Button Pressed: System DISARMED.\n");
                  }
              }

              osDelay(300); // Debounce delay
          }

          osDelay(50);
      }
  /* USER CODE END 5 */
}

